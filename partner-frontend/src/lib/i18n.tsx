const STORAGE_KEY = "quickpress_lang_v1";
const FIRST_TIME_KEY = "quickpress_lang_chosen_v1";

interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  t: (key: string, fallback?: string) => string;
  isLanguageModalOpen: boolean;
  openLanguageModal: () => void;
  closeLanguageModal: () => void;
}

const LanguageContext = createContext<LanguageContextType>({
  language: "en",
  setLanguage: () => {},
  t: (key, fallback) => fallback || key,
  isLanguageModalOpen: false,
  openLanguageModal: () => {},
  closeLanguageModal: () => {},
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLangState] = useState<LanguageCode>(() => {
    if (typeof window !== "undefined") {
      const saved = window.localStorage.getItem(STORAGE_KEY) as LanguageCode;
      if (saved && TRANSLATIONS[saved]) return saved;
    }
    return "en";
  });

  const [isLanguageModalOpen, setIsLanguageModalOpen] = useState(() => {
    if (typeof window !== "undefined") {
      const alreadyChosen = window.localStorage.getItem(FIRST_TIME_KEY);
      return !alreadyChosen; // Show modal on first open if not chosen yet
    }
    return false;
  });

  const setLanguage = (newLang: LanguageCode) => {
    if (TRANSLATIONS[newLang]) {
      setLangState(newLang);
      if (typeof window !== "undefined") {
        window.localStorage.setItem(STORAGE_KEY, newLang);
        window.localStorage.setItem(FIRST_TIME_KEY, "true");
      }
    }
  };

  const openLanguageModal = () => setIsLanguageModalOpen(true);
  const closeLanguageModal = () => {
    if (typeof window !== "undefined") {
      window.localStorage.setItem(FIRST_TIME_KEY, "true");
    }
    setIsLanguageModalOpen(false);
  };

  const t = useMemo(() => {
    return (key: string, fallback?: string): string => {
      const dict = TRANSLATIONS[language] || TRANSLATIONS.en;
      if (dict[key]) return dict[key];
      // Fallback to English
      if (TRANSLATIONS.en[key]) return TRANSLATIONS.en[key];
      return fallback || key;
    };
  }, [language]);

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        t,
        isLanguageModalOpen,
        openLanguageModal,
        closeLanguageModal,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
